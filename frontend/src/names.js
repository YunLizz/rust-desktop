function pick(arr, rng) {
  return arr[Math.floor(rng() * arr.length)];
}
function shuffle(arr, rng) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * 生成名字列表
 * @param {object} opts { type: 'person'|'book'|'place', style, gender, count, exclude }
 * @returns [{ name, meaning }]
 */
export function generateNames(opts = {}) {
  const {
    type = "person",
    style = "gufeng",
    gender = "中性",
    count = 8,
    exclude = [], // 已存在的名字，避免重复
  } = opts;

  const rng = Math.random;
  const pool = POOL[style]?.[gender] || POOL.gufeng["中性"];
  const out = [];
  const seen = new Set();

  let guard = 0;
  while (out.length < count && guard++ < 300) {
    if (type === "person") {
      const surname = pick(SURNAMES, rng);
      const chars = [pick(pool, rng)];
      // 50% 概率双字名
      if (rng() < 0.55) {
        let second = pick(pool, rng);
        while (second.c === chars[0].c) second = pick(pool, rng);
        chars.push(second);
      }
      const name = surname + chars.map((x) => x.c).join("");
      if (seen.has(name) || exclude.includes(name)) continue;
      seen.add(name);
      out.push({ name, meaning: `${surname}姓 · ${chars.map((x) => `${x.c}（${x.m}）`).join(" · ")}` });
    } else if (type === "book") {
      const words = BOOK_WORDS[style] || BOOK_WORDS.gufeng;
      const n = 2 + Math.floor(rng() * 2); // 2~3 词
      const picked = [];
      const pool2 = shuffle(words, rng);
      for (let i = 0; i < Math.min(n, pool2.length); i++) picked.push(pool2[i]);
      const name = picked.join("");
      if (seen.has(name) || exclude.includes(name)) continue;
      seen.add(name);
      out.push({ name: `《${name}》`, meaning: `${styleName(style)}风格 · ${picked.join(" + ")}` });
    } else {
      // place
      const words = PLACE_WORDS[style] || PLACE_WORDS.gufeng;
      const prefix = shuffle(words, rng).slice(0, 2);
      const name = prefix.join("");
      if (seen.has(name) || exclude.includes(name)) continue;
      seen.add(name);
      out.push({ name, meaning: `${styleName(style)}风格地名` });
    }
  }
  return out;
}

function styleName(style) {
  return { gufeng: "古风", xianxia: "仙侠玄幻", dushi: "都市", xihuan: "西幻" }[style] || style;
}

